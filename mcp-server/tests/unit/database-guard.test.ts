describe('terminal guard — database rules (refuse-only)', () => {
  it.each(REFUSED)('refuses: %s', (c) => {
    expect(db(c)).toBe('deny')
  })
  it.each(ALLOWED)('allows: %s', (c) => {
    expect(db(c)).toBe('allow')
  })
})

describe('terminal guard — database rules stay off unless asked', () => {
  it('does nothing when the database flag is off (the default)', () => {
    expect(judgeCommand('psql -c "drop table users"', { resolveAlias: NO_ALIASES }).verdict).toBe('allow')
  })
  it('judges a database command inside a package script when the flag is on', () => {
    expect(db('sh -c "redis-cli flushall"')).toBe('deny')
  })
})

describe('terminal guard — an escaped dollar is text, not a variable', () => {
  it('reads an escaped $ inside double quotes as a literal in bash and PowerShell', () => {
    expect(db('psql -c "select \'\\$1\' as price"')).toBe('allow')
    expect(db('psql -c "select \'`$1\' as price"', 'powershell')).toBe('allow')
    expect(db('psql -c "select \'\\$1\'; drop table t"')).toBe('deny')
  })
  it('still treats an unescaped $ or an escaped backslash before $ as a variable', () => {
    expect(db('psql -c "select $X"')).toBe('deny')
    expect(db('psql -c "select \\\\$X"')).toBe('deny')
    expect(db('psql -c "select $1 as price"', 'powershell')).toBe('deny')
  })
})

describe('database-guard — statement reader', () => {
  it('strips comments and string literals, keeps /*! */ code', () => {
    expect(stripSql("select 'drop table x'")).not.toMatch(/drop/i)
    expect(stripSql('select 1 /* drop */')).not.toMatch(/drop/i)
    expect(stripSql('/*!40000 drop table t */')).toMatch(/drop/i)
  })
  it('judges each statement', () => {
    expect(statementVerdict('select 1').ok).toBe(true)
    expect(statementVerdict('select 1; drop table t').ok).toBe(false)
    expect(statementVerdict("select 'update me'").ok).toBe(true)
  })
})
